"""Direct-reader backend for gen-state-storage.py's reflected retained graph.

The existing field registry owns every field number. These readers run only after
the canonical descriptor preflight; they never constitute a second wire schema.
"""


def generate_direct_group_reader(types, registry, name, go):
    root = "sipbridge/internal/engine.stateGroup"
    reachable = set()

    def visit(t):
        if t.startswith("*"):
            visit(t[1:])
        elif t.startswith("map["):
            key, val = t[4:].split("]", 1)
            visit(key)
            visit(val)
        elif t.startswith("[]") and t != "[]uint8":
            visit(t[2:])
        elif t in types and types[t]["kind"] == "struct" and t not in reachable:
            reachable.add(t)
            for field in types[t]["fields"]:
                visit(field["type"])

    visit(root)
    lines = [
        "// Code generated by scripts/gen-state-storage.py. DO NOT EDIT.",
        "package engine", "", "import (",
        '"google.golang.org/protobuf/encoding/protowire"',
        '"google.golang.org/protobuf/proto"',
        '"github.com/emiago/sipgo/sip/portable"',
        'pb "sipbridge/internal/controlpb"',
        '"sipbridge/internal/storagecodec"',
        '"sipbridge/internal/storagepb"', ")", "",
        "// readStateGroupDirect reads the canonical frame into independently owned",
        "// runtime values after complete preflight. The caller performs semantic",
        "// validation before publication; no temporary protobuf aggregate is built.",
        "func readStateGroupDirect(data []byte) (out stateGroup, err error) {",
        "  err = storagecodec.DecodeValidatedFrame(data, storagecodec.Group, (&storagepb.EngineStateGroup{}).ProtoReflect().Descriptor(), func(body []byte) error {",
        "    var readErr error", "    out, readErr = storageReadEngineStateGroup(body)",
        "    return readErr", "  })", "  if err != nil { return stateGroup{}, err }",
        "  return out, nil", "}", "",
        "type storageDirectField struct { number protowire.Number; bytes []byte; value uint64 }",
        "// All field types, counts and nesting have already passed preflight.",
        "func storageDirectNext(data []byte) (field storageDirectField, rest []byte, err error) {",
        "  number, typ, n := protowire.ConsumeTag(data)",
        "  if n < 0 { return field, nil, storagecodec.ErrRecord }",
        "  field.number = number", "  data = data[n:]", "  switch typ {",
        "  case protowire.BytesType: field.bytes, n = protowire.ConsumeBytes(data)",
        "  case protowire.VarintType: field.value, n = protowire.ConsumeVarint(data)",
        "  default: return field, nil, storagecodec.ErrRecord", "  }",
        "  if n < 0 { return field, nil, storagecodec.ErrRecord }",
        "  return field, data[n:], nil", "}", "",
        "func storageDirectCount(data []byte) (int, error) {",
        "  count := 0", "  for len(data) > 0 {",
        "    field, rest, err := storageDirectNext(data)",
        "    if err != nil || field.number != 1 { return 0, storagecodec.ErrRecord }",
        "    count++; data = rest", "  }", "  return count, nil", "}", "",
    ]

    def underlying(t):
        if t in types and types[t]["kind"] != "struct":
            return underlying(types[t]["kind"])
        return t

    def read_value(t, field, dest):
        """Assign one prevalidated field, with decoder-owned wire bytes."""
        target = go(t, "engine")
        if t.startswith("*pb:"):
            public = go(t[1:], "engine")
            return [f"{dest} = new({public})", f"if err := (proto.UnmarshalOptions{{RecursionLimit: storagecodec.MaxDepth}}).Unmarshal({field}.bytes, {dest}); err != nil {{ return out, err }}"]
        if t.startswith("*"):
            inner = t[1:]
            return [f"decoded, err := storageRead{name(inner)}({field}.bytes)", "if err != nil { return out, err }", f"{dest} = &decoded"]
        if t in types and types[t]["kind"] == "struct":
            return [f"decoded, err := storageRead{name(t)}({field}.bytes)", "if err != nil { return out, err }", f"{dest} = decoded"]
        base = underlying(t)
        if base == "[]uint8":
            return [f"{dest} = {target}(append([]byte{{}}, {field}.bytes...))"]
        if base == "string":
            return [f"{dest} = {target}({field}.bytes)"]
        if base == "bool":
            return [f"{dest} = {target}({field}.value != 0)"]
        return [f"{dest} = {target}({field}.value)"]

    collections = []
    for t in sorted(reachable):
        item = types[t]
        message = name(t)
        opaque_message = t == "github.com/emiago/sipgo/sip/portable.Message"
        lines += [f"func storageRead{message}(data []byte) (out {go(t, 'engine')}, err error) {{"]
        if opaque_message:
            lines += ["  var wire []byte", "  var transport, source, destination string"]
        lines += ["  for len(data) > 0 {", "    field, rest, err := storageDirectNext(data)", "    if err != nil { return out, err }", "    data = rest", "    switch field.number {"]
        for f in item["fields"]:
            ft = f["type"]
            number = registry[message][f["name"]]
            dest = "out." + f["name"]
            if opaque_message:
                dest = f["name"].lower()
            lines.append(f"    case {number}: // {f['name']}")
            if opaque_message and f["name"] == "Wire":
                # RestoreMessage takes its own immutable copy. Keep this
                # decoder-local slice borrowed until that single handoff.
                lines.append("      wire = field.bytes")
                continue
            if ft.startswith("map[") or ft.startswith("[]") and ft != "[]uint8":
                reader = "storageRead" + message + f["name"][0].upper() + f["name"][1:] + "Values"
                lines += [f"      decoded, err := {reader}(field.bytes)", "      if err != nil { return out, err }", f"      {dest} = decoded"]
                collections.append((reader, ft))
            else:
                lines += ["      " + line for line in read_value(ft, "field", dest)]
        lines += ["    default: return out, storagecodec.ErrRecord", "    }", "  }"]
        if opaque_message:
            lines.append("  out = portable.RestoreMessage(wire, transport, source, destination)")
        lines += ["  return out, nil", "}", ""]

    for reader, t in collections:
        lines += [f"func {reader}(data []byte) (out {go(t, 'engine')}, err error) {{", "  count, err := storageDirectCount(data)", "  if err != nil { return out, err }"]
        if t.startswith("map["):
            key, val = t[4:].split("]", 1)
            lines += [f"  out = make({go(t, 'engine')}, count)", "  for len(data) > 0 {", "    entry, rest, err := storageDirectNext(data)", "    if err != nil { return out, err }", "    data = rest", f"    var key {go(key, 'engine')}", f"    var value {go(val, 'engine')}", "    entryData := entry.bytes", "    for len(entryData) > 0 {", "      field, rest, err := storageDirectNext(entryData)", "      if err != nil { return out, err }", "      entryData = rest", "      switch field.number {", "      case 1:"]
            lines += ["        " + line for line in read_value(key, "field", "key")]
            lines.append("      case 2:")
            if val.startswith("*"):
                # Every nullable map value has a presence wrapper with field1.
                lines += ["        nullable := field.bytes", "        for len(nullable) > 0 {", "          field, rest, err := storageDirectNext(nullable)", "          if err != nil || field.number != 1 { return out, storagecodec.ErrRecord }", "          nullable = rest"]
                lines += ["          " + line for line in read_value(val, "field", "value")]
                lines.append("        }")
            else:
                lines += ["        " + line for line in read_value(val, "field", "value")]
            lines += ["      default: return out, storagecodec.ErrRecord", "      }", "    }", "    out[key] = value", "  }"]
        else:
            val = t[2:]
            lines += [f"  out = make({go(t, 'engine')}, 0, count)", "  for len(data) > 0 {", "    field, rest, err := storageDirectNext(data)", "    if err != nil { return out, err }", "    data = rest", f"    var value {go(val, 'engine')}"]
            lines += ["    " + line for line in read_value(val, "field", "value")]
            lines += ["    out = append(out, value)", "  }"]
        lines += ["  return out, nil", "}", ""]
    return "\n".join(lines)
